// Helper to get formatted date string for today and upcoming days (deterministic)
const getOffsetDate = (daysOffset: number): string => {
  const d = new Date('2026-10-11T00:00:00Z');
  d.setUTCDate(d.getUTCDate() + daysOffset);
  return d.toISOString().split('T')[0];
};

